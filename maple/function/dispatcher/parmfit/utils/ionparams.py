_ION_KEY_RE = re.compile(r"^([A-Z][a-z]?)(-?\d+)$")


def _parse_ion_key(ion_key: str) -> tuple[str, int]:
    match = _ION_KEY_RE.fullmatch(ion_key.strip())
    if match is None:
        raise ValueError(f"Invalid ion key {ion_key!r}.")
    return match.group(1), int(match.group(2))


def _normalize_element(element: str) -> str:
    stripped = element.strip()
    if not stripped:
        raise ValueError("Ion element is missing.")
    return stripped[0].upper() + stripped[1:].lower()


def _format_ion_key(element: str, formal_charge: int) -> str:
    return f"{_normalize_element(element)}{int(formal_charge)}"


def infer_ion_identity(residue: dict | str) -> tuple[str, int, str]:
    if isinstance(residue, dict) and "formal_charge" in residue:
        atoms = residue.get("atoms", [])
        element = atoms[0]["element"] if atoms else residue["resname"]
        formal_charge = int(residue["formal_charge"])
        ion_key = _format_ion_key(element, formal_charge)
        return _normalize_element(element), formal_charge, ion_key

    resname = residue["resname"] if isinstance(residue, dict) else str(residue)
    key = ION_RESNAME_TO_KEY.get(resname.strip().upper())
    if key is None:
        raise ValueError(f"Unsupported or ambiguous ion residue name {resname!r}.")
    element, formal_charge = _parse_ion_key(key)
    return element, formal_charge, key


def lookup_ion_radius(*, watm: str, element: str, formal_charge: int, ion_key: str | None = None) -> float:
    table = ION_LJ_BY_WATM[watm]
    if ion_key is not None:
        if ion_key in table:
            return float(table[ion_key])

    candidates: list[tuple[int, float]] = []
    for key, radius in table.items():
        key_element, charge = _parse_ion_key(key)
        if key_element == element:
            candidates.append((charge, float(radius)))
    if not candidates:
        raise ValueError(f"No ion radius data is available for element {element!r} in water model {watm!r}.")

    _charge, radius = min(
        candidates,
        key=lambda item: (abs(item[0] - formal_charge), 0 if item[0] <= formal_charge else 1, abs(item[0])),
    )
    return float(radius)


def collect_gaussian_readradii_entries(model: dict, *, watm: str | None = None) -> list[tuple[str, float]]:
    ion_residues = [residue for residue in model["residues"] if residue.get("kind") == "ion"]
    if not ion_residues:
        return []
    entries: list[tuple[str, float]] = []
    for residue in ion_residues:
        element, formal_charge, ion_key = infer_ion_identity(residue)
        radius = lookup_ion_radius(
            watm=watm,
            element=element,
            formal_charge=formal_charge,
            ion_key=ion_key,
        )
        entries.append((element, radius))
    return entries


def infer_ion_frcmod_name(*, watm: str, ionm: str, residue: dict | str) -> str:
    _element, formal_charge, _ion_key = infer_ion_identity(residue)

    if watm in {"tip3p", "spce", "tip4pew"}:
        if formal_charge in {-1, 1}:
            prefix = "frcmod.ions1lm_"
        elif formal_charge in {2, 3, 4}:
            prefix = "frcmod.ions234lm_"
        else:
            prefix = "frcmod.ionslm_"
    else:
        prefix = "frcmod.ionslm_"

    suffix = {
        "hfe": f"hfe_{watm}",
        "cm": f"126_{watm}",
        "12_6": f"126_{watm}",
        "iod": "iod" if prefix == "frcmod.ions1lm_" else f"iod_{watm}",
        "12_6_4": f"1264_{watm}",
    }[ionm]
    return prefix + suffix
